class DataCleaner:
    def __init__(self, df):
        self.df = df.copy()
        self.original_shape = df.shape
        
    def remove_outliers_iqr(self, columns=None, threshold=1.5):
        if columns is None:
            columns = self.df.select_dtypes(include=[np.number]).columns
            
        df_clean = self.df.copy()
        for col in columns:
            if col in df_clean.columns:
                Q1 = df_clean[col].quantile(0.25)
                Q3 = df_clean[col].quantile(0.75)
                IQR = Q3 - Q1
                lower_bound = Q1 - threshold * IQR
                upper_bound = Q3 + threshold * IQR
                df_clean = df_clean[(df_clean[col] >= lower_bound) & (df_clean[col] <= upper_bound)]
        
        removed_count = len(self.df) - len(df_clean)
        self.df = df_clean
        return removed_count
    
    def impute_missing(self, strategy='mean', columns=None):
        if columns is None:
            columns = self.df.select_dtypes(include=[np.number]).columns
            
        df_imputed = self.df.copy()
        for col in columns:
            if col in df_imputed.columns and df_imputed[col].isnull().any():
                if strategy == 'mean':
                    fill_value = df_imputed[col].mean()
                elif strategy == 'median':
                    fill_value = df_imputed[col].median()
                elif strategy == 'mode':
                    fill_value = df_imputed[col].mode()[0]
                else:
                    fill_value = 0
                
                df_imputed[col] = df_imputed[col].fillna(fill_value)
        
        self.df = df_imputed
        return self.df.isnull().sum().sum()
    
    def standardize_columns(self, columns=None):
        if columns is None:
            columns = self.df.select_dtypes(include=[np.number]).columns
            
        df_scaled = self.df.copy()
        for col in columns:
            if col in df_scaled.columns:
                mean = df_scaled[col].mean()
                std = df_scaled[col].std()
                if std > 0:
                    df_scaled[col] = (df_scaled[col] - mean) / std
        
        self.df = df_scaled
        return self.df
    
    def get_cleaned_data(self):
        return self.df
    
    def get_cleaning_stats(self):
        return {
            'original_rows': self.original_shape[0],
            'cleaned_rows': len(self.df),
            'rows_removed': self.original_shape[0] - len(self.df),
            'original_columns': self.original_shape[1],
            'cleaned_columns': self.df.shape[1]
        }

