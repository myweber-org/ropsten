def remove_duplicates(data_list):
    """
    Remove duplicate entries from a list while preserving order.
    
    Args:
        data_list: A list containing potentially duplicate items.
    
    Returns:
        A new list with duplicates removed.
    """
    seen = set()
    result = []
    
    for item in data_list:
        if item not in seen:
            seen.add(item)
            result.append(item)
    
    return result

def clean_numeric_data(values):
    """
    Clean numeric data by converting strings to floats and removing None values.
    
    Args:
        values: A list of numeric values as strings or numbers.
    
    Returns:
        A list of cleaned float values.
    """
    cleaned = []
    
    for value in values:
        if value is None:
            continue
        
        try:
            num = float(value)
            cleaned.append(num)
        except (ValueError, TypeError):
            continue
    
    return cleaned

def validate_email_format(email):
    """
    Basic email format validation.
    
    Args:
        email: String containing email address.
    
    Returns:
        Boolean indicating if email format is valid.
    """
    if not email or not isinstance(email, str):
        return False
    
    parts = email.split('@')
    
    if len(parts) != 2:
        return False
    
    if not parts[0] or not parts[1]:
        return False
    
    if '.' not in parts[1]:
        return False
    
    return True

