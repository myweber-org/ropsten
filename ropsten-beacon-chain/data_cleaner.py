def normalize_data(df, columns, method='minmax'):
    """Normalize data using specified method."""
    df_norm = df.copy()
    for col in columns:
        if col in df.columns:
            if method == 'minmax':
                df_norm[col] = (df[col] - df[col].min()) / (df[col].max() - df[col].min())
            elif method == 'zscore':
                df_norm[col] = stats.zscore(df[col])
    return df_norm

